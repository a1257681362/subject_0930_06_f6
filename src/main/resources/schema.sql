-- ============================================================
-- F4 高空作业排班
-- 读取风速/降雨/雷电天气窗口，结合人员资质、装备可用性与维修时长生成候选班次；
-- 天气窗口按 风机+起止时刻 唯一归并：补传/补录/重试只形成一条可用结果；
-- 窗口收窄自动预警但不静默改期；作业开始前二次确认天气；
-- 延期保留原计划与通知回执；过期资质人员不能被排入任务；
-- 每个作业任务至多一个确认班次（唯一可用排班结果）。
-- ============================================================

-- 人员：高空作业资质类型与有效期；过期资质不能被排入任务
CREATE TABLE IF NOT EXISTS t_worker (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    worker_no VARCHAR(64) NOT NULL,
    name VARCHAR(64) NOT NULL,
    qualification_type VARCHAR(32) NOT NULL,
    qualification_valid_until TIMESTAMP NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_worker_no UNIQUE (worker_no)
);

-- 装备：可用状态与可用窗口 [available_from, available_to)，空表示不限
CREATE TABLE IF NOT EXISTS t_equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_no VARCHAR(64) NOT NULL,
    name VARCHAR(128) NOT NULL,
    equipment_type VARCHAR(32) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'AVAILABLE',
    available_from TIMESTAMP NULL,
    available_to TIMESTAMP NULL,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_equipment_no UNIQUE (equipment_no)
);

-- 天气窗口：风速/降雨/雷电；同一风机的重叠窗口为同一逻辑窗口，
-- 补传/补录/重试归并为一条并递增 revision（起止与读数以最新上报为准）
CREATE TABLE IF NOT EXISTS t_weather_window (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_no VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    window_start TIMESTAMP NOT NULL,
    window_end TIMESTAMP NOT NULL,
    max_wind_speed DOUBLE NOT NULL,
    rainfall_mm DOUBLE NOT NULL,
    lightning_risk VARCHAR(16) NOT NULL,
    source VARCHAR(64) NULL,
    revision INT NOT NULL DEFAULT 1,
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_weather_window_no UNIQUE (window_no),
    CONSTRAINT uk_weather_window_span UNIQUE (turbine_id, window_start, window_end)
);

-- 高空作业任务：关联缺陷，资质要求 + 人数 + 装备类型 + 维修时长
CREATE TABLE IF NOT EXISTS t_maintenance_task (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_no VARCHAR(64) NOT NULL,
    turbine_id BIGINT NOT NULL,
    defect_id BIGINT NULL,
    required_qualification VARCHAR(32) NOT NULL,
    required_workers INT NOT NULL DEFAULT 2,
    required_equipment_type VARCHAR(32) NULL,
    estimated_duration_hours INT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'PLANNING',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_maintenance_task_no UNIQUE (task_no)
);

-- 班次：候选/确认/进行中/完成/被取代/取消；同一任务同一窗口唯一；
-- 首次延期把当前计划固化为 original_start/original_end（原计划），之后不再改变
CREATE TABLE IF NOT EXISTS t_work_shift (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shift_no VARCHAR(64) NOT NULL,
    task_id BIGINT NOT NULL,
    window_id BIGINT NOT NULL,
    shift_start TIMESTAMP NOT NULL,
    shift_end TIMESTAMP NOT NULL,
    original_start TIMESTAMP NULL,
    original_end TIMESTAMP NULL,
    postpone_count INT NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'CANDIDATE',
    create_by BIGINT NULL,
    create_time TIMESTAMP NULL,
    update_by BIGINT NULL,
    update_time TIMESTAMP NULL,
    CONSTRAINT uk_work_shift_no UNIQUE (shift_no),
    CONSTRAINT uk_work_shift_task_window UNIQUE (task_id, window_id)
);

-- 班次人员/装备分配
